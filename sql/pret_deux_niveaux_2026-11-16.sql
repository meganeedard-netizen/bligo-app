-- BliGO - Prêt à deux niveaux / dépôts de la bibliothèque départementale (16/11/2026)
--
-- Demande du Sud Corse (RDV du 12/11/2026), précisée par Mégane le 16/11 :
-- la bibliothèque départementale (BDP) prête ses documents aux bibliothèques
-- communales, qui les prêtent à leurs usagers.
--   - L'usager commande un document de la BDP dans sa bibliothèque communale ;
--     la demande part vers la BDP, qui l'envoie avec la navette (mensuelle, par ex.).
--   - Arrivé dans la bibliothèque communale, le document y reste « en dépôt »
--     sans date de fin (un mois comme un an) : au retour de l'usager, il ne
--     repart pas vers la BDP.
--   - La BDP sait où sont ses documents et peut en demander le retour à tout
--     moment, en particulier quand une autre bibliothèque le demande et que
--     le dépôt dure depuis au moins un mois (délai réglable).
--   - Revenu à la BDP, le document repart vers la bibliothèque qui l'attendait.
--
-- S'appuie sur les transferts existants (transfers, transfer_send/receive,
-- écran Transferts) : on ajoute le type de transfert, la table des dépôts,
-- les demandes à la BDP et la date de la prochaine navette.

-- 1) La BDP du réseau, la navette, le délai avant rappel conseillé
alter table public.communes add column if not exists is_bdp boolean not null default false;
comment on column public.communes.is_bdp is 'Bibliothèque départementale de prêt du réseau : ses documents sont déposés dans les bibliothèques communales (prêt à deux niveaux).';
alter table public.communities add column if not exists navette_next_date date;
alter table public.communities add column if not exists navette_label text;
alter table public.communities add column if not exists depot_recall_min_days integer not null default 30;

-- 2) Type de transfert
alter table public.transfers add column if not exists kind text not null default 'standard';
do $$ begin
  alter table public.transfers add constraint transfers_kind_check check (kind in ('standard', 'depot', 'depot_retour'));
exception when duplicate_object then null; end $$;

-- 3) Dépôts : un document de la BDP présent dans une bibliothèque communale
create table if not exists public.depots (
  id bigint generated by default as identity primary key,
  copy_id bigint not null references public.book_copies(id) on delete cascade,
  bdp_commune_id bigint not null references public.communes(id),
  library_commune_id bigint not null references public.communes(id),
  started_at timestamptz not null default now(),
  recall_requested_at timestamptz,
  recall_requested_by uuid,
  recall_for_commune_id bigint references public.communes(id),
  recall_reservation_id bigint references public.reservations(id) on delete set null,
  recall_reason text,
  ended_at timestamptz
);
create unique index if not exists depots_one_open_per_copy on public.depots(copy_id) where ended_at is null;
create index if not exists depots_library_open on public.depots(library_commune_id) where ended_at is null;
alter table public.depots enable row level security;
drop policy if exists "Les agents voient les dépôts" on public.depots;
create policy "Les agents voient les dépôts" on public.depots for select using (public.is_agent() or public.is_super_admin());

-- 4) Demandes faites à la BDP quand aucun exemplaire n'est sur ses rayons
create table if not exists public.depot_requests (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  bdp_commune_id bigint not null references public.communes(id),
  library_commune_id bigint not null references public.communes(id),
  reservation_id bigint references public.reservations(id) on delete set null,
  requested_by uuid,
  created_at timestamptz not null default now(),
  status text not null default 'open' check (status in ('open', 'recall_sent', 'fulfilled', 'cancelled')),
  fulfilled_at timestamptz
);
create index if not exists depot_requests_open on public.depot_requests(bdp_commune_id) where status in ('open', 'recall_sent');
alter table public.depot_requests enable row level security;
drop policy if exists "Les agents voient les demandes de dépôt" on public.depot_requests;
create policy "Les agents voient les demandes de dépôt" on public.depot_requests for select using (public.is_agent() or public.is_super_admin());

-- 5) Outils
create or replace function public.bdp_of_commune(p_commune_id bigint)
returns bigint
language sql stable security definer set search_path = public
as $$
  select b.id from public.communes c
    join public.communes b on b.community_id = c.community_id and b.is_bdp
   where c.id = p_commune_id
   order by b.id limit 1;
$$;

create or replace function public._open_depot(p_copy_id bigint, p_library bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare v_owner bigint;
begin
  select owner_commune_id into v_owner from public.book_copies where id = p_copy_id;
  update public.depots set ended_at = now() where copy_id = p_copy_id and ended_at is null;
  if p_library is distinct from v_owner then
    insert into public.depots (copy_id, bdp_commune_id, library_commune_id) values (p_copy_id, v_owner, p_library);
  end if;
end;
$$;

-- Transfert demandé, sans doublon
create or replace function public._request_transfer(p_copy_id bigint, p_from bigint, p_to bigint, p_kind text, p_reservation_id bigint, p_notes text)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if exists (select 1 from public.transfers where copy_id = p_copy_id and status in ('requested', 'in_transit')) then
    return false;
  end if;
  insert into public.transfers (copy_id, from_commune_id, to_commune_id, status, requested_by, reservation_id, notes, kind)
  values (p_copy_id, p_from, p_to, 'requested', auth.uid(), p_reservation_id, p_notes, p_kind);
  return true;
end;
$$;

-- 6) Préparer une réservation : un document de la BDP déposé dans une AUTRE
--    bibliothèque n'est pas pris directement chez elle, la demande passe par la BDP.
create or replace function public.prepare_reservation(p_reservation_id bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_reservation public.reservations;
  v_user_commune bigint;
  v_copy public.book_copies;
  v_here bigint;
  v_dest_name text;
  v_owner_bdp boolean;
  v_bdp bigint;
begin
  if not (public.is_agent() or public.is_super_admin()) then
    raise exception 'Accès réservé aux agents';
  end if;

  select * into v_reservation from public.reservations where id = p_reservation_id;
  if v_reservation.id is null then
    return jsonb_build_object('ok', false, 'message', 'Réservation introuvable.');
  end if;
  if v_reservation.status <> 'preparation' then
    return jsonb_build_object('ok', false, 'message', 'Cette réservation n''est plus en préparation.');
  end if;
  if exists (select 1 from public.transfers where reservation_id = p_reservation_id and status in ('requested', 'in_transit')) then
    return jsonb_build_object('ok', true, 'needs_transfer', true, 'message', 'Le document est déjà demandé, il arrivera avec la navette.');
  end if;
  if exists (select 1 from public.depot_requests where reservation_id = p_reservation_id and status in ('open', 'recall_sent')) then
    return jsonb_build_object('ok', true, 'needs_transfer', true, 'message', 'Déjà demandé à la bibliothèque départementale, qui fait revenir un exemplaire.');
  end if;

  select commune_id into v_user_commune from public.profiles where id = v_reservation.user_id;
  v_here := coalesce(v_reservation.pickup_commune_id, v_user_commune, public.agent_commune_id());

  select c.* into v_copy
  from public.book_copies c
  join public.communes o on o.id = c.owner_commune_id
  where c.book_id = v_reservation.book_id and c.status = 'available'
    and not (o.is_bdp and c.current_commune_id <> c.owner_commune_id and c.current_commune_id <> v_here)
    and not exists (select 1 from public.transfers t where t.copy_id = c.id and t.status in ('requested', 'in_transit'))
  order by (c.current_commune_id = v_here) desc, c.id
  limit 1;

  if v_copy.id is null then
    -- Exemplaires de la BDP tous déposés ailleurs : demande à la BDP.
    select c.owner_commune_id into v_bdp
      from public.book_copies c join public.communes o on o.id = c.owner_commune_id
     where c.book_id = v_reservation.book_id and o.is_bdp and c.status not in ('withdrawn', 'lost')
     limit 1;
    if v_bdp is not null then
      insert into public.depot_requests (book_id, bdp_commune_id, library_commune_id, reservation_id, requested_by)
      values (v_reservation.book_id, v_bdp, v_here, p_reservation_id, auth.uid());
      return jsonb_build_object('ok', true, 'needs_transfer', true,
        'message', 'Les exemplaires de la bibliothèque départementale sont en dépôt dans d''autres bibliothèques : demande transmise à la BDP, qui fera revenir un exemplaire. L''usager sera prévenu à l''arrivée.');
    end if;
    return jsonb_build_object('ok', false, 'message', 'Aucun exemplaire disponible pour ce livre en ce moment, dans aucune médiathèque du réseau.');
  end if;

  if v_copy.current_commune_id = v_here then
    update public.reservations set status = 'pret' where id = p_reservation_id;
    return jsonb_build_object('ok', true, 'needs_transfer', false, 'message', 'Réservation prête à récupérer.');
  end if;

  select is_bdp into v_owner_bdp from public.communes where id = v_copy.owner_commune_id;
  update public.book_copies set status = 'reserved' where id = v_copy.id;
  perform public._request_transfer(v_copy.id, v_copy.current_commune_id, v_here,
    case when v_owner_bdp and v_copy.current_commune_id = v_copy.owner_commune_id then 'depot' else 'standard' end,
    p_reservation_id, 'Demandé pour une réservation en préparation');

  select name into v_dest_name from public.communes where id = v_copy.current_commune_id;
  return jsonb_build_object('ok', true, 'needs_transfer', true,
    'message', 'Aucun exemplaire ici : demandé à ' || coalesce(v_dest_name, 'une autre médiathèque') || '. L''usager sera prévenu à l''arrivée.');
end;
$$;

-- 7) Réception d'un transfert : ouvre ou ferme le dépôt ; un document revenu
--    à la BDP repart vers la bibliothèque qui l'attend.
create or replace function public.transfer_receive(p_barcode text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_copy public.book_copies;
  v_transfer public.transfers;
  v_book public.books;
  v_has_reservation boolean := false;
  v_owner_bdp boolean;
  v_depot public.depots;
  v_req public.depot_requests;
  v_next_to bigint;
  v_next_resa bigint;
  v_next_name text;
begin
  if not (public.is_agent() or public.is_super_admin()) then
    raise exception 'Accès réservé aux agents';
  end if;

  select * into v_copy from public.book_copies where barcode = trim(p_barcode);
  if v_copy.id is null then
    return jsonb_build_object('ok', false, 'message', 'Code-barres inconnu.');
  end if;
  select * into v_book from public.books where id = v_copy.book_id;

  select * into v_transfer from public.transfers
   where copy_id = v_copy.id and status = 'in_transit' order by sent_at limit 1;
  if v_transfer.id is null then
    return jsonb_build_object('ok', false, 'message', 'Ce livre n''était pas annoncé en transfert.');
  end if;

  update public.transfers set status = 'received', received_at = now(), received_by = auth.uid() where id = v_transfer.id;
  v_has_reservation := v_transfer.reservation_id is not null;

  update public.book_copies
     set current_commune_id = v_transfer.to_commune_id,
         status = case when v_has_reservation then 'reserved' else 'available' end
   where id = v_copy.id;

  select is_bdp into v_owner_bdp from public.communes where id = v_copy.owner_commune_id;

  if coalesce(v_owner_bdp, false) then
    if v_transfer.to_commune_id <> v_copy.owner_commune_id then
      -- Arrivé dans une bibliothèque communale : nouveau dépôt.
      perform public._open_depot(v_copy.id, v_transfer.to_commune_id);
    else
      -- Revenu à la BDP : fin du dépôt, puis départ vers qui l'attend.
      select * into v_depot from public.depots where copy_id = v_copy.id and ended_at is null;
      update public.depots set ended_at = now() where copy_id = v_copy.id and ended_at is null;

      v_next_to := v_depot.recall_for_commune_id;
      v_next_resa := v_depot.recall_reservation_id;
      if v_next_to is not null then
        update public.depot_requests set status = 'fulfilled', fulfilled_at = now()
         where status in ('open', 'recall_sent') and book_id = v_copy.book_id and library_commune_id = v_next_to
           and reservation_id is not distinct from v_next_resa;
      else
        select * into v_req from public.depot_requests
         where status in ('open', 'recall_sent') and book_id = v_copy.book_id
         order by created_at limit 1;
        if v_req.id is not null then
          v_next_to := v_req.library_commune_id;
          v_next_resa := v_req.reservation_id;
          update public.depot_requests set status = 'fulfilled', fulfilled_at = now() where id = v_req.id;
        end if;
      end if;

      if v_next_to is not null then
        update public.book_copies set status = 'reserved' where id = v_copy.id;
        perform public._request_transfer(v_copy.id, v_copy.owner_commune_id, v_next_to, 'depot', v_next_resa,
          'Demandé par une bibliothèque du réseau');
        select name into v_next_name from public.communes where id = v_next_to;
        return jsonb_build_object('ok', true, 'title', v_book.title, 'author', v_book.author, 'for_reservation', false,
          'shelf_location', v_copy.shelf_location,
          'message', 'Retour enregistré. Attendu par ' || coalesce(v_next_name, 'une autre bibliothèque') || ' : à mettre dans la prochaine navette.');
      end if;
    end if;
  end if;

  if v_has_reservation then
    update public.reservations set status = 'pret' where id = v_transfer.reservation_id;
    insert into public.notifications (user_id, message)
    select r.user_id, 'Ton livre « ' || v_book.title || ' » est arrivé, tu peux venir le récupérer.'
      from public.reservations r where r.id = v_transfer.reservation_id;
  end if;

  return jsonb_build_object(
    'ok', true, 'title', v_book.title, 'author', v_book.author,
    'for_reservation', v_has_reservation, 'shelf_location', v_copy.shelf_location,
    'message', case
      when v_has_reservation then 'Arrivée enregistrée. À mettre de côté, un usager l''attend.'
      when coalesce(v_owner_bdp, false) and v_transfer.to_commune_id <> v_copy.owner_commune_id then 'Arrivée enregistrée : document de la bibliothèque départementale en dépôt ici, à ranger en rayon.'
      else 'Arrivée enregistrée, à ranger en rayon.'
    end);
end;
$$;

-- 8) Retour d'un livre : un document de la BDP reste en dépôt dans la
--    bibliothèque, sauf si la BDP en a demandé le retour.
create or replace function public.scan_return(p_barcode text, p_condition text default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_copy public.book_copies;
  v_book public.books;
  v_loan public.loans;
  v_here bigint;
  v_returns_anywhere boolean;
  v_late boolean := false;
  v_transfer_created boolean := false;
  v_late_fee_cents integer := 0;
  v_user_commune bigint;
  v_grace_days integer;
  v_days_late integer;
  v_should_flag boolean := false;
  v_owner_bdp boolean;
  v_depot public.depots;
  v_bdp_recall boolean := false;
  v_kept_in_depot boolean := false;
begin
  if not (public.is_agent() or public.is_super_admin()) then
    raise exception 'Accès réservé aux agents';
  end if;
  if p_condition is not null and p_condition not in ('bon', 'mauvais') then
    raise exception 'État de retour invalide : % (attendu bon ou mauvais)', p_condition;
  end if;

  select * into v_copy from public.book_copies where barcode = trim(p_barcode);
  if v_copy.id is null then
    return jsonb_build_object('ok', false, 'message', 'Code-barres inconnu.');
  end if;
  select * into v_book from public.books where id = v_copy.book_id;

  v_here := coalesce(public.agent_commune_id(), v_copy.current_commune_id);
  select is_bdp into v_owner_bdp from public.communes where id = v_copy.owner_commune_id;
  v_owner_bdp := coalesce(v_owner_bdp, false);

  select co.returns_anywhere into v_returns_anywhere
    from public.communes cm join public.communities co on co.id = cm.community_id where cm.id = v_here;
  v_returns_anywhere := coalesce(v_returns_anywhere, true);

  if not v_owner_bdp and not v_returns_anywhere and v_here is distinct from v_copy.owner_commune_id then
    return jsonb_build_object('ok', false,
      'message', 'Ce livre appartient à une autre médiathèque, et le contrat impose de le rendre sur place.');
  end if;

  select * into v_loan from public.loans where copy_id = v_copy.id and returned_at is null;
  if v_loan.id is not null then
    v_late := now() > v_loan.due_at;
    select commune_id into v_user_commune from public.profiles where id = v_loan.user_id;
    select coalesce(late_fee_grace_days, 7) into v_grace_days from public.communes where id = v_user_commune;
    v_grace_days := coalesce(v_grace_days, 7);
    v_days_late := greatest(0, extract(day from (now() - v_loan.due_at))::int);
    v_late_fee_cents := public.calculate_late_fee_cents(v_loan.due_at, now(), v_user_commune);
    v_should_flag := (p_condition = 'mauvais') or (v_days_late > v_grace_days);

    update public.loans set returned_at = now(), returned_at_commune_id = v_here, returned_by_agent = auth.uid()
     where id = v_loan.id;

    if v_should_flag then
      perform public.set_user_flagged(v_loan.user_id, true,
        case
          when p_condition = 'mauvais' and v_days_late > v_grace_days then 'Livre rendu abîmé et en retard'
          when p_condition = 'mauvais' then 'Livre rendu abîmé'
          else 'Retard de plus de ' || v_grace_days || ' jours'
        end);
    end if;
    if v_loan.reservation_id is not null then
      update public.reservations set status = 'expiree' where id = v_loan.reservation_id;
    end if;
  end if;

  update public.book_copies
     set status = 'available', current_commune_id = v_here, condition = coalesce(p_condition, condition)
   where id = v_copy.id;

  if v_owner_bdp then
    if v_here = v_copy.owner_commune_id then
      update public.depots set ended_at = now() where copy_id = v_copy.id and ended_at is null;
    else
      select * into v_depot from public.depots where copy_id = v_copy.id and ended_at is null;
      if v_depot.id is null or v_depot.library_commune_id <> v_here then
        -- Rendu dans une autre bibliothèque du réseau : le dépôt suit le document
        -- (un rappel en cours est conservé).
        perform public._open_depot(v_copy.id, v_here);
        if v_depot.id is not null and v_depot.recall_requested_at is not null then
          update public.depots
             set recall_requested_at = v_depot.recall_requested_at, recall_requested_by = v_depot.recall_requested_by,
                 recall_for_commune_id = v_depot.recall_for_commune_id, recall_reservation_id = v_depot.recall_reservation_id,
                 recall_reason = v_depot.recall_reason
           where copy_id = v_copy.id and ended_at is null;
        end if;
        select * into v_depot from public.depots where copy_id = v_copy.id and ended_at is null;
      end if;
      if v_depot.recall_requested_at is not null then
        v_bdp_recall := true;
        v_transfer_created := public._request_transfer(v_copy.id, v_here, v_copy.owner_commune_id, 'depot_retour', null,
          'Retour demandé par la bibliothèque départementale');
        v_transfer_created := true;
      else
        v_kept_in_depot := true;
      end if;
    end if;
  elsif v_here is distinct from v_copy.owner_commune_id then
    v_transfer_created := public._request_transfer(v_copy.id, v_here, v_copy.owner_commune_id, 'standard', null,
      'Retour rendu dans une autre médiathèque');
    v_transfer_created := true;
  end if;

  return jsonb_build_object(
    'ok', true, 'title', v_book.title, 'author', v_book.author,
    'had_loan', v_loan.id is not null, 'was_late', v_late, 'late_fee_cents', v_late_fee_cents,
    'user_flagged', v_should_flag, 'needs_transfer', v_transfer_created,
    'depot_bdp', v_owner_bdp, 'bdp_recall', v_bdp_recall,
    'shelf_location', v_copy.shelf_location,
    'message', case
      when v_bdp_recall then 'Retour enregistré. La bibliothèque départementale a demandé ce document : à renvoyer avec la prochaine navette.'
      when v_transfer_created then 'Retour enregistré. Ce livre appartient à une autre médiathèque, il est à renvoyer.'
      when v_late_fee_cents > 0 then 'Retour enregistré, avec retard : ' || to_char(v_late_fee_cents / 100.0, 'FM999990.00') || ' € de pénalité.'
      when v_late then 'Retour enregistré, avec du retard (dans la franchise, aucune pénalité).'
      when v_loan.id is null then 'Aucun prêt en cours pour cet exemplaire, il est remis en rayon.'
      when v_kept_in_depot then 'Retour enregistré. Document de la bibliothèque départementale en dépôt ici : à remettre en rayon.'
      else 'Retour enregistré.'
    end);
end;
$$;

-- 9) La BDP demande le retour d'un document déposé
create or replace function public.depot_recall(p_copy_id bigint, p_request_id bigint default null, p_reason text default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_copy public.book_copies;
  v_depot public.depots;
  v_req public.depot_requests;
  v_loan public.loans;
  v_lib text;
begin
  select * into v_copy from public.book_copies where id = p_copy_id;
  if v_copy.id is null then raise exception 'Exemplaire introuvable'; end if;
  if not (public.is_super_admin() or (public.is_agent() and public.agent_commune_id() = v_copy.owner_commune_id)) then
    raise exception 'Seule la bibliothèque départementale propriétaire peut demander le retour.';
  end if;
  select * into v_depot from public.depots where copy_id = p_copy_id and ended_at is null;
  if v_depot.id is null then
    return jsonb_build_object('ok', false, 'message', 'Ce document n''est pas en dépôt.');
  end if;
  if p_request_id is not null then
    select * into v_req from public.depot_requests where id = p_request_id;
    update public.depot_requests set status = 'recall_sent' where id = p_request_id and status = 'open';
  end if;

  update public.depots
     set recall_requested_at = now(), recall_requested_by = auth.uid(),
         recall_for_commune_id = v_req.library_commune_id, recall_reservation_id = v_req.reservation_id,
         recall_reason = coalesce(nullif(trim(p_reason), ''), case when v_req.id is not null then 'Demandé par une autre bibliothèque' end)
   where id = v_depot.id;

  select name into v_lib from public.communes where id = v_depot.library_commune_id;
  select * into v_loan from public.loans where copy_id = p_copy_id and returned_at is null;

  if v_loan.id is null and v_copy.status = 'available' and v_copy.current_commune_id = v_depot.library_commune_id then
    perform public._request_transfer(p_copy_id, v_depot.library_commune_id, v_copy.owner_commune_id, 'depot_retour', null,
      'Retour demandé par la bibliothèque départementale');
    return jsonb_build_object('ok', true, 'message', 'Retour demandé à ' || coalesce(v_lib, 'la bibliothèque') || ' : le document reviendra avec la prochaine navette.');
  end if;
  return jsonb_build_object('ok', true, 'message', 'Retour demandé à ' || coalesce(v_lib, 'la bibliothèque')
    || case when v_loan.id is not null then ' : le document est prêté à un usager jusqu''au ' || to_char(v_loan.due_at, 'DD/MM') || ', il repartira dès son retour.'
            else '.' end);
end;
$$;

-- Annuler un rappel
create or replace function public.depot_recall_cancel(p_copy_id bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare v_copy public.book_copies;
begin
  select * into v_copy from public.book_copies where id = p_copy_id;
  if not (public.is_super_admin() or (public.is_agent() and public.agent_commune_id() = v_copy.owner_commune_id)) then
    raise exception 'Non autorisé';
  end if;
  if exists (select 1 from public.transfers where copy_id = p_copy_id and kind = 'depot_retour' and status = 'in_transit') then
    return jsonb_build_object('ok', false, 'message', 'Le document est déjà en route vers la bibliothèque départementale.');
  end if;
  update public.transfers set status = 'cancelled' where copy_id = p_copy_id and kind = 'depot_retour' and status = 'requested';
  update public.depot_requests r set status = 'open'
    from public.depots d
   where d.copy_id = p_copy_id and d.ended_at is null and r.status = 'recall_sent'
     and r.book_id = v_copy.book_id and r.library_commune_id = d.recall_for_commune_id;
  update public.depots set recall_requested_at = null, recall_requested_by = null, recall_for_commune_id = null,
         recall_reservation_id = null, recall_reason = null
   where copy_id = p_copy_id and ended_at is null;
  return jsonb_build_object('ok', true, 'message', 'Demande de retour annulée.');
end;
$$;

-- 10) Une bibliothèque communale demande un document de la BDP pour son fonds
create or replace function public.depot_request_book(p_book_id bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_here bigint := public.agent_commune_id();
  v_bdp bigint;
  v_copy public.book_copies;
begin
  if not public.is_agent() or v_here is null then raise exception 'Réservé aux agents'; end if;
  select commune_id into v_bdp from public.books where id = p_book_id;
  if not exists (select 1 from public.communes where id = v_bdp and is_bdp) then
    select c.owner_commune_id into v_bdp from public.book_copies c join public.communes o on o.id = c.owner_commune_id and o.is_bdp
     where c.book_id = p_book_id limit 1;
  end if;
  if v_bdp is null then
    return jsonb_build_object('ok', false, 'message', 'Ce document n''appartient pas à la bibliothèque départementale.');
  end if;
  if v_bdp = v_here then
    return jsonb_build_object('ok', false, 'message', 'Ce document est déjà dans votre fonds.');
  end if;

  select c.* into v_copy from public.book_copies c
   where c.book_id = p_book_id and c.owner_commune_id = v_bdp and c.current_commune_id = v_bdp and c.status = 'available'
     and not exists (select 1 from public.transfers t where t.copy_id = c.id and t.status in ('requested', 'in_transit'))
   order by c.id limit 1;

  if v_copy.id is not null then
    update public.book_copies set status = 'reserved' where id = v_copy.id;
    perform public._request_transfer(v_copy.id, v_bdp, v_here, 'depot', null, 'Dépôt demandé par la bibliothèque');
    return jsonb_build_object('ok', true, 'message', 'Demande envoyée : le document arrivera avec la prochaine navette.');
  end if;

  if exists (select 1 from public.depot_requests where book_id = p_book_id and library_commune_id = v_here and reservation_id is null and status in ('open', 'recall_sent')) then
    return jsonb_build_object('ok', true, 'message', 'Déjà demandé à la bibliothèque départementale.');
  end if;
  insert into public.depot_requests (book_id, bdp_commune_id, library_commune_id, requested_by)
  values (p_book_id, v_bdp, v_here, auth.uid());
  return jsonb_build_object('ok', true, 'message', 'Tous les exemplaires sont déjà en dépôt ailleurs : demande transmise à la bibliothèque départementale.');
end;
$$;

-- Annuler une demande (bibliothèque qui l'a faite ou BDP)
create or replace function public.depot_request_cancel(p_request_id bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare v_req public.depot_requests;
begin
  select * into v_req from public.depot_requests where id = p_request_id;
  if v_req.id is null then raise exception 'Demande introuvable'; end if;
  if not (public.is_super_admin() or (public.is_agent() and public.agent_commune_id() in (v_req.library_commune_id, v_req.bdp_commune_id))) then
    raise exception 'Non autorisé';
  end if;
  update public.depot_requests set status = 'cancelled' where id = p_request_id and status in ('open', 'recall_sent');
  return jsonb_build_object('ok', true, 'message', 'Demande annulée.');
end;
$$;

-- 11) Navette : date de la prochaine, réglée par la BDP
create or replace function public.set_navette(p_date date, p_label text default null, p_min_days integer default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare v_comm bigint;
begin
  if not (public.is_super_admin() or (public.is_agent() and exists (select 1 from public.communes where id = public.agent_commune_id() and is_bdp))) then
    raise exception 'Réservé à la bibliothèque départementale';
  end if;
  select community_id into v_comm from public.communes where id = public.agent_commune_id();
  update public.communities
     set navette_next_date = p_date,
         navette_label = coalesce(nullif(trim(p_label), ''), navette_label),
         depot_recall_min_days = coalesce(p_min_days, depot_recall_min_days)
   where id = v_comm;
  return jsonb_build_object('ok', true, 'message', 'Navette enregistrée.');
end;
$$;

-- 12) Vue d'ensemble pour l'écran « Dépôts » du logiciel agent
create or replace function public.depot_overview()
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  v_here bigint := public.agent_commune_id();
  v_me public.communes;
  v_comm public.communities;
  v_bdp bigint;
  v_depots jsonb;
  v_requests jsonb;
  v_libraries jsonb;
begin
  if not (public.is_agent() or public.is_super_admin()) then raise exception 'Réservé aux agents'; end if;
  select * into v_me from public.communes where id = v_here;
  select * into v_comm from public.communities where id = v_me.community_id;
  v_bdp := case when v_me.is_bdp then v_me.id else public.bdp_of_commune(v_here) end;
  if v_bdp is null then
    return jsonb_build_object('has_bdp', false);
  end if;

  select coalesce(jsonb_agg(x order by x->>'library_name', x->>'started_at'), '[]'::jsonb) into v_depots from (
    select jsonb_build_object(
      'copy_id', d.copy_id, 'barcode', c.barcode, 'book_id', b.id, 'title', b.title, 'author', b.author,
      'library_id', d.library_commune_id, 'library_name', lib.name,
      'started_at', d.started_at, 'days', (now()::date - d.started_at::date),
      'copy_status', c.status, 'loan_due_at', l.due_at,
      'recall_requested_at', d.recall_requested_at, 'recall_reason', d.recall_reason,
      'recall_for_name', rf.name,
      'transfer_status', t.status) x
    from public.depots d
    join public.book_copies c on c.id = d.copy_id
    join public.books b on b.id = c.book_id
    join public.communes lib on lib.id = d.library_commune_id
    left join public.communes rf on rf.id = d.recall_for_commune_id
    left join public.loans l on l.copy_id = c.id and l.returned_at is null
    left join lateral (select status from public.transfers where copy_id = c.id and kind = 'depot_retour' and status in ('requested', 'in_transit') order by id desc limit 1) t on true
    where d.ended_at is null and d.bdp_commune_id = v_bdp
      and (v_me.is_bdp or d.library_commune_id = v_here)
  ) s;

  select coalesce(jsonb_agg(x order by x->>'created_at'), '[]'::jsonb) into v_requests from (
    select jsonb_build_object(
      'id', r.id, 'book_id', b.id, 'title', b.title, 'author', b.author, 'status', r.status,
      'library_id', r.library_commune_id, 'library_name', lib.name, 'created_at', r.created_at,
      'for_user', p.full_name,
      'candidates', (
        select coalesce(jsonb_agg(jsonb_build_object(
          'copy_id', d.copy_id, 'barcode', c.barcode, 'library_name', l2.name,
          'days', (now()::date - d.started_at::date), 'copy_status', c.status, 'loan_due_at', ln.due_at,
          'recalled', d.recall_requested_at is not null)
          order by d.started_at), '[]'::jsonb)
        from public.depots d
        join public.book_copies c on c.id = d.copy_id
        join public.communes l2 on l2.id = d.library_commune_id
        left join public.loans ln on ln.copy_id = c.id and ln.returned_at is null
        where d.ended_at is null and c.book_id = r.book_id and d.library_commune_id <> r.library_commune_id)) x
    from public.depot_requests r
    join public.books b on b.id = r.book_id
    join public.communes lib on lib.id = r.library_commune_id
    left join public.reservations rs on rs.id = r.reservation_id
    left join public.profiles p on p.id = rs.user_id
    where r.status in ('open', 'recall_sent') and r.bdp_commune_id = v_bdp
      and (v_me.is_bdp or r.library_commune_id = v_here)
  ) s;

  -- Par lieu de lecture : documents en dépôt, prêtés en ce moment, prêts de l'année
  select coalesce(jsonb_agg(x order by x->>'name'), '[]'::jsonb) into v_libraries from (
    select jsonb_build_object(
      'id', cm.id, 'name', cm.name, 'address', cm.address, 'is_bdp', cm.is_bdp,
      'in_depot', (select count(*) from public.depots d where d.ended_at is null and d.library_commune_id = cm.id and d.bdp_commune_id = v_bdp),
      'on_loan', (select count(*) from public.depots d join public.loans l on l.copy_id = d.copy_id and l.returned_at is null
                   where d.ended_at is null and d.library_commune_id = cm.id and d.bdp_commune_id = v_bdp),
      'loans_year', (select count(*) from public.loans l join public.book_copies c on c.id = l.copy_id
                      where c.owner_commune_id = v_bdp and l.borrowed_at_commune_id = cm.id
                        and l.borrowed_at >= date_trunc('year', now()))) x
    from public.communes cm
    where cm.community_id = v_me.community_id
  ) s;

  return jsonb_build_object(
    'has_bdp', true, 'is_bdp', v_me.is_bdp, 'bdp_id', v_bdp,
    'bdp_name', (select name from public.communes where id = v_bdp),
    'navette_next_date', v_comm.navette_next_date, 'navette_label', v_comm.navette_label,
    'recall_min_days', v_comm.depot_recall_min_days,
    'depots', v_depots, 'requests', v_requests, 'libraries', v_libraries);
end;
$$;

-- 13) Pour l'usager : ses commandes en route (navette)
create or replace function public.my_navette_info()
returns jsonb
language sql stable security definer set search_path = public
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'reservation_id', r.id,
    'etape', case when dr.id is not null then 'attente_bdp' when t.status = 'in_transit' then 'en_route' else 'demande' end,
    'navette_date', co.navette_next_date,
    'from_bdp', coalesce(o.is_bdp, dr.id is not null))), '[]'::jsonb)
  from public.reservations r
  join public.profiles p on p.id = r.user_id
  left join public.communes cm on cm.id = coalesce(r.pickup_commune_id, p.commune_id)
  left join public.communities co on co.id = cm.community_id
  left join lateral (select * from public.transfers where reservation_id = r.id and status in ('requested', 'in_transit') order by id desc limit 1) t on true
  left join public.book_copies c on c.id = t.copy_id
  left join public.communes o on o.id = c.owner_commune_id
  left join lateral (select id from public.depot_requests where reservation_id = r.id and status in ('open', 'recall_sent') limit 1) dr on true
  where r.user_id = auth.uid() and r.status = 'preparation' and (t.id is not null or dr.id is not null);
$$;

-- Catalogue de l'usager : la BDP de son réseau (pour afficher ses documents)
